#!/usr/bin/env python3
"""Generate EaglerFont.java from the official Minecraft 26.1.2 client jar.

Source of truth (vanilla, byte-exact):
  - assets/minecraft/textures/font/ascii.png   (128x128, 16x16 grid of 8x8 cells)
  - assets/minecraft/font/include/default.json (chars grid, ascent 7)
  - assets/minecraft/font/include/space.json   (space advance = 4)

Width algorithm = net.minecraft.client.gui.font.providers.BitmapProvider$Definition
  .getActualGlyphWidth: scan cell columns right-to-left; the first column that
  contains any pixel with alpha != 0 gives width = columnIndex + 1 (0 if blank).
Advance = round(width * height/glyphHeight) + 1 = width + 1 at 1x scale.
Glyph pixels are packed row-major into a long: bit (row*8 + (7-col)).
"""
import json, subprocess, os

JAR = '/home/z/my-project/mc-client-26.1.2.jar'
OUT = '/home/z/my-project/eaglercraft-26.1.2/sources/teavm/java/net/lax1dude/eaglercraft/v2_6/adapter/EaglerFont.java'

from PIL import Image

tmp = '/home/z/my-project/work/fontgen'
os.makedirs(tmp, exist_ok=True)
subprocess.run(['unzip', '-o', '-j', JAR, 'assets/minecraft/textures/font/ascii.png', '-d', tmp],
               check=True, capture_output=True)
subprocess.run(['unzip', '-o', JAR, 'assets/minecraft/font/include/default.json',
                'assets/minecraft/font/include/space.json', '-d', tmp],
               check=True, capture_output=True)

img = Image.open(os.path.join(tmp, 'ascii.png')).convert('RGBA')
assert img.size == (128, 128), f"unexpected atlas size {img.size}"
px = img.load()

grid = json.load(open(os.path.join(tmp, 'assets/minecraft/font/include/default.json')))['providers']
prov = [p for p in grid if p.get('file', '').endswith('ascii.png')][0]
assert prov['ascent'] == 7
rows = prov['chars']
assert len(rows) == 16 and all(len(r) == 16 for r in rows)

space = json.load(open(os.path.join(tmp, 'assets/minecraft/font/include/space.json')))
space_prov = [p for p in space['providers'] if p.get('type') == 'space'][0]
space_adv = space_prov['advances'][' ']
assert space_adv == 4, space

def cell_of(ch):
    for r in range(16):
        c = rows[r].find(ch)
        if c >= 0 and ord(rows[r][c]) == ord(ch):
            return c, r
    return None

def actual_width(cx, cy):
    for w in range(7, -1, -1):
        for y in range(8):
            if px[cx * 8 + w, cy * 8 + y][3] != 0:
                return w + 1
    return 0

entries = []
for code in range(0x20, 0x7F):
    ch = chr(code)
    cell = cell_of(ch)
    assert cell, f"{ch!r} missing from grid"
    cx, cy = cell
    w = actual_width(cx, cy)
    bits = 0
    for y in range(8):
        for x in range(8):
            if px[cx * 8 + x, cy * 8 + y][3] != 0:
                bits |= 1 << (y * 8 + (7 - x))
    adv = space_adv if ch == ' ' else w + 1
    entries.append((code, ch, bits, w, adv))

def esc(ch):
    return {
        '\\': '\\\\', '"': '\\"', "'": "\\'",
        '\x20': '\\x20', '\x7f': '\\x7f',
    }.get(ch, ch)

lines = []
lines.append('package net.lax1dude.eaglercraft.v2_6.adapter;')
lines.append('')
lines.append('/**')
lines.append(' * The vanilla Minecraft bitmap font for the TeaVM 2D GUI renderer')
lines.append(' * ({@link EaglerGuiImpl}), extracted byte-exact from the official')
lines.append(' * 26.1.2 client jar: assets/minecraft/textures/font/ascii.png with')
lines.append(' * the chars grid of font/include/default.json (ascent 7) and the')
lines.append(' * space advance of font/include/space.json (4).')
lines.append(' *')
lines.append(' * <p>Covers the printable ASCII range 0x20-0x7E. Each 8x8 glyph cell')
lines.append(' * is packed row-major into a {@code long}: bit {@code (row * 8 + (7 - col))}')
lines.append(' * is set when the pixel at {@code (col, row)} is on, row 0 at the top,')
lines.append(' * col 0 at the left. Widths follow vanilla\'s BitmapProvider scan')
lines.append(' * (right-to-left first non-empty column + 1) and advances are')
lines.append(' * {@code width + 1}, except space which vanilla pins to 4. This file')
lines.append(' * is GENERATED by {@code scripts/gen_font.py} - edit the script, not')
lines.append(' * this table.</p>')
lines.append(' */')
lines.append('public final class EaglerFont {')
lines.append('')
lines.append('        /** Width of a glyph cell in pixels (vanilla ascii.png cell). */')
lines.append('        public static final int CELL_WIDTH = 8;')
lines.append('')
lines.append('        /** Height of a glyph cell in pixels (= vanilla font line height). */')
lines.append('        public static final int GLYPH_HEIGHT = 8;')
lines.append('')
lines.append('        /** Baseline row: glyphs render rows 0..6 above it, row 7 descends. */')
lines.append('        public static final int ASCENT = 7;')
lines.append('')
lines.append('        /** Advance of the space character (vanilla include/space.json). */')
lines.append('        public static final int SPACE_ADVANCE = 4;')
lines.append('')
lines.append('        /** First supported character (0x20, space). */')
lines.append('        public static final char FIRST_CHAR = 0x20;')
lines.append('')
lines.append('        /** Last supported character (0x7E, tilde). */')
lines.append('        public static final char LAST_CHAR = 0x7E;')
lines.append('')
lines.append('        private EaglerFont() {')
lines.append('        }')
lines.append('')
lines.append('        /**')
lines.append('         * Returns whether the character has glyph data.')
lines.append('         */')
lines.append('        public static boolean hasGlyph(char c) {')
lines.append('                return c >= FIRST_CHAR && c <= LAST_CHAR;')
lines.append('        }')
lines.append('')
lines.append('        /**')
lines.append('         * Returns the raw 64-bit glyph cell pattern for the character, or')
lines.append('         * the pattern for \'?\' when the character is unsupported.')
lines.append('         */')
lines.append('        public static long glyph(char c) {')
lines.append('                if (!hasGlyph(c)) {')
lines.append('                        return GLYPHS[\'?\' - FIRST_CHAR];')
lines.append('                }')
lines.append('                return GLYPHS[c - FIRST_CHAR];')
lines.append('        }')
lines.append('')
lines.append('        /**')
lines.append('         * Returns the vanilla advance of the character in pixels')
lines.append('         * (width + 1; space is pinned to 4). Unsupported characters fall')
lines.append('         * back to the \'?\' advance so cursor math stays consistent with')
lines.append('         * what {@link #glyph} draws.')
lines.append('         */')
lines.append('        public static int advance(char c) {')
lines.append('                if (!hasGlyph(c)) {')
lines.append('                        c = \'?\';')
lines.append('                }')
lines.append('                return ADVANCES[c - FIRST_CHAR];')
lines.append('        }')
lines.append('')
lines.append('        /**')
lines.append('         * Returns whether pixel {@code (col, row)} of the glyph is on.')
lines.append('         */')
lines.append('        public static boolean isPixelSet(long glyph, int col, int row) {')
lines.append('                if (col < 0 || col >= CELL_WIDTH || row < 0 || row >= GLYPH_HEIGHT) {')
lines.append('                        return false;')
lines.append('                }')
lines.append('                return (glyph >>> (row * 8 + (7 - col)) & 0x1L) != 0L;')
lines.append('        }')
lines.append('')
lines.append('        /** The packed glyph table, index 0 = character 0x20. */')
lines.append('        private static final long[] GLYPHS = {')
for code, ch, bits, w, adv in entries:
    lines.append(f"        0x{bits:012X}L, // 0x{code:02X} '{esc(ch)}' w={w} adv={adv}")
lines.append('        };')
lines.append('')
lines.append('        /** Vanilla advances per character, index 0 = character 0x20. */')
lines.append('        private static final int[] ADVANCES = {')
per_line = []
for code, ch, bits, w, adv in entries:
    per_line.append(f"{adv}")
    if len(per_line) == 16:
        lines.append('        ' + ', '.join(per_line) + ',')
        per_line = []
if per_line:
    lines.append('        ' + ', '.join(per_line))
lines.append('        };')
lines.append('}')
lines.append('')

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(lines))
print(f"wrote {OUT}: {len(entries)} glyphs")
blank = [ch for _, ch, b, w, a in entries if w == 0]
print("blank glyphs:", blank)
narrow = [(ch, a) for _, ch, b, w, a in entries if a < 6]
print("narrow advances:", narrow)
