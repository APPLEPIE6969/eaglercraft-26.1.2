#!/usr/bin/env python3
"""Generate SkyTimeline.java from the official Minecraft 26.1.2 client jar.

Ground truth: data/minecraft/timeline/day.json (period 24000, clock
minecraft:overworld) extracted from the client jar, plus the two base
colors from data/minecraft/dimension_type/overworld.json attributes
(minecraft:visual/sky_color #78a7ff, minecraft:visual/fog_color #c0d8ff).

Track semantics replicated by the generator:
- "modifier": "multiply" tracks (sky_color, fog_color) hold ARGB
  multipliers; the dimension base color is multiplied per channel.
  Coverage is WRAPPED: the key list is extended by one period on both
  ends so every t in [0, 24000) interpolates.
- sky_light_color x sky_light_factor are merged at bake time into one
  RGB factor (the world-shader dimming uniform), also WRAPPED.
- star_brightness and sunrise_sunset_color hold absolute values and are
  GATED: outside keyframe coverage the value is the attribute default 0
  (no stars / no sunrise fan at high noon, exactly like vanilla).
- sun_angle / moon_angle / star_angle use a cubic_bezier ease over one
  period starting at t=6000; generated as closed-form methods (the two
  same-tick keyframes 360.0 -> 0.0 are the wrap seam).
- moon_phase is not generated: visual/moon_phase in timeline/moon.json
  (period 192000) maps 1:1 to the classic day-count formula
  floor(dayTime / 24000) % 8 over the MoonPhase enum order.

The output table in SkyTimeline.java is GENERATED - edit this script,
not the file.
"""

import json
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

JAR = Path('/tmp/my-project/mc-client-26.1.2.jar')
OUT = Path(__file__).resolve().parent.parent / 'sources/teavm/java/net/minecraft/client/renderer/SkyTimeline.java'

PERIOD = 24000
NOON = 6000


def load_day_timeline():
    with zipfile.ZipFile(JAR) as zf:
        day = json.loads(zf.read('data/minecraft/timeline/day.json'))
        dim = json.loads(zf.read('data/minecraft/dimension_type/overworld.json'))
    return day, dim


def parse_argb(v):
    """Timeline colors arrive as either '#rrggbb' strings or signed ints."""
    if isinstance(v, str):
        v = v.lstrip('#')
        if len(v) == 6:
            v = 'ff' + v
        return int(v, 16)
    return int(v) & 0xFFFFFFFF


def keyframes(day, track):
    return [(kf['ticks'], kf['value']) for kf in day['tracks'][track]['keyframes']]


def wrapped_argb(track):
    """[(tick, argb)] extended by one period on both ends."""
    keys = [(t, parse_argb(v)) for t, v in track]
    first_t, first_v = keys[0]
    last_t, last_v = keys[-1]
    return [(last_t - PERIOD, last_v)] + keys + [(first_t + PERIOD, first_v)]


def merged_sky_light(day):
    """sky_light_color (ARGB) x sky_light_factor (float) -> [(tick, (r,g,b))]."""
    colors = [(t, parse_argb(v)) for t, v in keyframes(day, 'minecraft:visual/sky_light_color')]
    factors = dict(keyframes(day, 'minecraft:visual/sky_light_factor'))
    # The two tracks share their keyframe ticks; multiply per channel.
    out = []
    for t, argb in colors:
        f = factors[t]
        r = ((argb >> 16) & 0xFF) / 255.0 * f
        g = ((argb >> 8) & 0xFF) / 255.0 * f
        b = (argb & 0xFF) / 255.0 * f
        out.append((t, (r, g, b)))
    first_t, first_v = out[0]
    last_t, last_v = out[-1]
    return [(last_t - PERIOD, last_v)] + out + [(first_t + PERIOD, first_v)]


def gated_floats(track):
    return [(t, float(v)) for t, v in track]


def gated_argb(track):
    return [(t, parse_argb(v)) for t, v in track]


def fmt_float(v):
    return '%.6gf' % v


def main():
    day, dim = load_day_timeline()
    sky_base = parse_argb(dim['attributes']['minecraft:visual/sky_color'])
    fog_base = parse_argb(dim['attributes']['minecraft:visual/fog_color'])

    sky_mult = wrapped_argb(keyframes(day, 'minecraft:visual/sky_color'))
    fog_mult = wrapped_argb(keyframes(day, 'minecraft:visual/fog_color'))
    sky_light = merged_sky_light(day)
    star = gated_floats(keyframes(day, 'minecraft:visual/star_brightness'))
    sunrise = gated_argb(keyframes(day, 'minecraft:visual/sunrise_sunset_color'))

    ease = day['tracks']['minecraft:visual/sun_angle']['ease']['cubic_bezier']

    lines = []
    lines.append('package net.minecraft.client.renderer;')
    lines.append('')
    lines.append('/**')
    lines.append(' * GENERATED by scripts/gen_sky_timeline.py from the official')
    lines.append(' * Minecraft 26.1.2 client jar - edit the script, not this file.')
    lines.append(' *')
    lines.append(' * Ground truth (verbatim from the jar):')
    lines.append(' * <ul>')
    lines.append(' *   <li>data/minecraft/timeline/day.json (period 24000 ticks,')
    lines.append(' *       clock minecraft:overworld) - sky/fog color multipliers,')
    lines.append(' *       sky light, star brightness, sunrise/sunset colors.</li>')
    lines.append(' *   <li>data/minecraft/dimension_type/overworld.json attributes -')
    lines.append(' *       the base sky color #%06x and fog color #%06x the'
                % (sky_base & 0xFFFFFF, fog_base & 0xFFFFFF))
    lines.append(' *       multiply tracks apply to.</li>')
    lines.append(' *   <li>The sun/moon/star angle ease cubic_bezier(%s,' % ', '.join(fmt_float(v) for v in ease[:2]))
    lines.append(' *       %s) shared by all three angle tracks (the two'
                 % ', '.join(fmt_float(v) for v in ease[2:]))
    lines.append(' *       same-tick keyframes at t=6000 are the wrap seam).</li>')
    lines.append(' * </ul>')
    lines.append(' *')
    lines.append(' * <p>Encoding: WRAPPED tracks (sky/fog multipliers, sky light)')
    lines.append(' * carry one extra keyframe past each end of the period so every')
    lines.append(' * t in [0, 24000) interpolates; GATED tracks (star brightness,')
    lines.append(' * sunrise/sunset color) fall back to zero outside coverage,')
    lines.append(' * matching vanilla\'s keyframe-coverage semantics.</p>')
    lines.append(' */')
    lines.append('public final class SkyTimeline {')
    lines.append('')
    lines.append('        public static final int PERIOD = %d;' % PERIOD)
    lines.append('        /** Timeline origin of the angle tracks (noon). */')
    lines.append('        public static final int ANGLE_ORIGIN = %d;' % NOON)
    lines.append('')
    lines.append('        /** dimension_type/overworld.json: minecraft:visual/sky_color. */')
    lines.append('        public static final int SKY_COLOR_BASE = 0x%08X;' % sky_base)
    lines.append('        /** dimension_type/overworld.json: minecraft:visual/fog_color. */')
    lines.append('        public static final int FOG_COLOR_BASE = 0x%08X;' % fog_base)
    lines.append('')
    lines.append('        /** cubic_bezier control points of the angle tracks (x0,y0,x1,y1). */')
    lines.append('        public static final float[] ANGLE_EASE = {%s};'
                 % ', '.join(fmt_float(v) for v in ease))
    lines.append('')

    def argb_table(name, rows, comment):
        lines.append('        /** %s */' % comment)
        lines.append('        public static final int[] %s = {' % name)
        for i in range(0, len(rows), 3):
            chunk = ', '.join('%d, 0x%08X' % (t, v) for t, v in rows[i:i + 3])
            lines.append('                        ' + chunk + ',')
        lines.append('        };')
        lines.append('')

    argb_table('SKY_COLOR_MULT', sky_mult,
               'WRAPPED sky_color multiplier track: {tick, ARGB}.')
    argb_table('FOG_COLOR_MULT', fog_mult,
               'WRAPPED fog_color multiplier track: {tick, ARGB}.')
    argb_table('SUNRISE_SUNSET', sunrise,
               'GATED sunrise_sunset_color track: {tick, ARGB}, alpha included.')

    lines.append('        /** WRAPPED sky light dimming (color x factor merged): {tick, r, g, b}. */')
    lines.append('        public static final float[] SKY_LIGHT = {')
    for i in range(0, len(sky_light), 2):
        chunk = ', '.join('%d, %s, %s, %s' % (t, fmt_float(r), fmt_float(g), fmt_float(b))
                          for t, (r, g, b) in sky_light[i:i + 2])
        lines.append('                        ' + chunk + ',')
    lines.append('        };')
    lines.append('')
    lines.append('        /** GATED star_brightness track: {tick, value}; 0 outside coverage. */')
    lines.append('        public static final float[] STAR_BRIGHTNESS = {')
    for i in range(0, len(star), 3):
        chunk = ', '.join('%d, %s' % (t, fmt_float(v)) for t, v in star[i:i + 3])
        lines.append('                        ' + chunk + ',')
    lines.append('        };')
    lines.append('}')

    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote %s (%d lines)' % (OUT, len(lines)))
    print('sky base #%06x, fog base #%06x, %d sky mult keys, %d sunrise keys, %d star keys'
          % (sky_base & 0xFFFFFF, fog_base & 0xFFFFFF, len(sky_mult), len(sunrise), len(star)))


if __name__ == '__main__':
    main()
