        /** Last supported character (0x7E, tilde). */
        public static final char LAST_CHAR = 0x7E;

        private EaglerFont() {
        }

        /**
         * Returns whether the character has glyph data.
         */
        public static boolean hasGlyph(char c) {
                return c >= FIRST_CHAR && c <= LAST_CHAR;
        }

        /**
         * Returns the raw 64-bit glyph cell pattern for the character, or
         * the pattern for '?' when the character is unsupported.
         */
        public static long glyph(char c) {
                if (!hasGlyph(c)) {
                        return GLYPHS['?' - FIRST_CHAR];
                }
                return GLYPHS[c - FIRST_CHAR];
        }

        /**
         * Returns the vanilla advance of the character in pixels
         * (width + 1; space is pinned to 4). Unsupported characters fall
         * back to the '?' advance so cursor math stays consistent with
         * what {@link #glyph} draws.
         */
        public static int advance(char c) {
                if (!hasGlyph(c)) {
                        c = '?';
                }
                return ADVANCES[c - FIRST_CHAR];
        }

        /**
         * Returns whether pixel {@code (col, row)} of the glyph is on.
         */
        public static boolean isPixelSet(long glyph, int col, int row) {
                if (col < 0 || col >= CELL_WIDTH || row < 0 || row >= GLYPH_HEIGHT) {
                        return false;
                }
                return (glyph >>> (row * 8 + (7 - col)) & 0x1L) != 0L;
        }

